import { cpSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const source = resolve(process.env.WEBZJS_SOURCE || `${root}/.cache/WebZjs`);
const dest = resolve(root, '.cache/snap');
mkdirSync(dest, { recursive: true });
cpSync(resolve(source, 'packages/snap'), dest, { recursive: true });
cpSync(resolve(source, 'packages/webzjs-keys'), resolve(dest, 'keys'), { recursive: true });
const pkg = JSON.parse(readFileSync(resolve(dest, 'package.json'), 'utf8'));
pkg.dependencies['@chainsafe/webzjs-keys'] = 'file:./keys';
pkg.scripts = { build: 'mm-snap build', start: 'mm-snap serve' };
pkg.devDependencies = { '@metamask/snaps-cli': '^6.5.2', typescript: '^5.9.3', '@types/react': '^18.3.0', prettier: '^3.6.0' };
writeFileSync(resolve(dest, 'package.json'), JSON.stringify(pkg, null, 2));
const manifestPath = resolve(dest, 'snap.manifest.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const origin = new URL(process.env.CHECKOUT_ORIGIN || 'http://localhost:3000').origin;
manifest.initialPermissions['endowment:rpc'].allowedOrigins = [origin];
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
console.log('Prepared testnet Snap. Run: npm install --prefix .cache/snap && npm run build --prefix .cache/snap && npm start --prefix .cache/snap');
